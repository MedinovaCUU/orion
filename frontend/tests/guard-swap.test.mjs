import assert from 'node:assert/strict';
import { applyGuardSwap, guardSwapCandidates } from '../src/modules/service-planning/helpers/guardSwap.ts';
const row=(date,app,eng,extra={})=>({weekendStart:date,phase:'programado',applicativoOriginal:app,applicativoAssigned:app,ingenieriaOriginal:eng,ingenieriaAssigned:eng,...extra});
const rows=[row('2026-10-03','Ana','Diego'),row('2026-10-10','Martha','Guillermo',{note:'Viaje confirmado'}),row('2026-11-07','Martha','Hector'),row('2026-09-05','Martha','Guillermo',{phase:'historico'})];
const draft={applicativo:'Martha',ingenieria:'Guillermo',note:'Permuta acordada'};
const original={'2026-12-01':{weekendStart:'2026-12-01',note:'Conservar'}};
const next=applyGuardSwap(rows,original,'2026-10-03',draft,{applicativo:'2026-10-10',ingenieria:'2026-10-10'},'Coordinador');
assert.equal(next['2026-10-03'].applicativo,'Martha');
assert.equal(next['2026-10-03'].ingenieria,'Guillermo');
assert.equal(next['2026-10-10'].applicativo,'Ana');
assert.equal(next['2026-10-10'].ingenieria,'Diego');
assert.equal(next['2026-10-10'].note,'Viaje confirmado');
assert.equal(next['2026-10-03'].updatedAt,next['2026-10-10'].updatedAt);
assert.deepEqual(next['2026-12-01'],original['2026-12-01']);
assert.equal(Object.keys(original).length,1);
const cross=applyGuardSwap(rows,original,'2026-10-03',{...draft,ingenieria:'Diego'},{applicativo:'2026-11-07'},'Admin');
assert.equal(cross['2026-11-07'].applicativo,'Ana');
assert.equal(cross['2026-11-07'].ingenieria,undefined);
assert.equal(guardSwapCandidates(rows,rows[0],'applicativo','Martha').length,2);
assert.throws(()=>applyGuardSwap(rows,original,'2026-10-03',draft,{applicativo:'2026-09-05'},'Admin'));
const changed=rows.map(r=>r.weekendStart==='2026-10-03'?{...r,applicativoAssigned:'Martha',ingenieriaAssigned:'Guillermo'}:r.weekendStart==='2026-10-10'?{...r,applicativoAssigned:'Ana',ingenieriaAssigned:'Diego'}:r);
const undo=applyGuardSwap(changed,next,'2026-10-03',{applicativo:'Ana',ingenieria:'Diego',note:''},{applicativo:'2026-10-10',ingenieria:'2026-10-10'},'Admin');
assert.equal(undo['2026-10-03'],undefined);
assert.equal(undo['2026-10-10'].applicativo,undefined);
assert.equal(undo['2026-10-10'].note,'Viaje confirmado');
console.log('PASS: reciprocal swap, both areas, cross-month target, preserve notes, reject historic target, reverse swap.');
