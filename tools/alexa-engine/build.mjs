#!/usr/bin/env node
// ORION · bundles the DRI engine for the Alexa Edge Function.
//   node tools/alexa-engine/build.mjs          → writes supabase/functions/alexa/engine.bundle.js
//   node tools/alexa-engine/build.mjs --check  → fails if the committed bundle is stale
// Uses the rolldown that ships with the frontend's Vite 8. lotDates.ts is swapped for lotDatesMx.ts (explicit
// America/Mexico_City), because Edge Functions run in UTC.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
const require = createRequire(join(root, 'frontend/package.json'));
const { rolldown } = require('rolldown');
const out = join(root, 'supabase/functions/alexa/engine.bundle.js');
const lotDates = join(root, 'frontend/src/modules/dri/utils/lotDates.ts');
const forbidden = [/supabaseClient/, /@supabase\/supabase-js/, /import\.meta\.env/, /\breact\b/];

const bundle = await rolldown({
  input: join(here, 'entry.ts'),
  platform: 'neutral',
  treeshake: true,
  logLevel: 'warn',
  plugins: [
    {
      name: 'orion-server-swaps',
      async resolveId(source, importer) {
        if (!importer) return null;
        const r = await this.resolve(source, importer, { skipSelf: true });
        if (r?.id === lotDates) return join(here, 'lotDatesMx.ts');
        if (r && forbidden.some((re) => re.test(r.id))) throw new Error(`${r.id} must not reach the server bundle (imported by ${importer})`);
        return null;
      },
    },
  ],
});
const { output } = await bundle.generate({ format: 'esm', minify: false, comments: false });
await bundle.close();
const code = `// Generated by tools/alexa-engine/build.mjs from frontend/src/modules/dri. Do not edit.\n// @ts-nocheck\n${output[0].code}`;
for (const re of forbidden) if (re.test(code)) throw new Error(`bundle contains ${re}`);

if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (current !== code) {
    console.error('engine.bundle.js is stale: run node tools/alexa-engine/build.mjs');
    process.exit(1);
  }
  console.log('engine.bundle.js is up to date');
} else {
  writeFileSync(out, code);
  console.log(`engine.bundle.js ${(code.length / 1024).toFixed(0)} KiB`);
}
