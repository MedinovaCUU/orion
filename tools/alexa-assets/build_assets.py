"""ORION · Alexa assets.

Builds the skill icons (108/512 px, from the dark Orion icon) and the Echo Show assets that the
`alexa` Edge Function serves itself (dark starfield background + the Orion mark), so the skill does
not depend on the web deploy. Run from the repo root:

    python3 tools/alexa-assets/build_assets.py
"""
import base64
import io
import random
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[2]
ICON = ROOT / "renders/orion_brand/iconos/apple-touch-icon-1024-oscuro.png"
MARK = ROOT / "renders/orion_brand/icono_1024_alpha.png"
SKILL_IMAGES = ROOT / "alexa/skill-package/assets/images"
OUT_TS = ROOT / "supabase/functions/alexa/assets.generated.ts"


def icons():
    SKILL_IMAGES.mkdir(parents=True, exist_ok=True)
    src = Image.open(ICON).convert("RGB")
    for size, name in ((108, "es-MX_smallIcon.png"), (512, "es-MX_largeIcon.png")):
        src.resize((size, size), Image.LANCZOS).save(SKILL_IMAGES / name, optimize=True)


def background(w=1280, h=800):
    """Deep space, a faint cyan/red nebula on the right (where the data sits) and sparse stars."""
    rnd = random.Random(7)
    base = Image.new("RGB", (w, h), (6, 9, 16))
    glow = Image.new("RGB", (w, h), (0, 0, 0))
    d = ImageDraw.Draw(glow)
    d.ellipse((int(w * 0.55), int(h * -0.35), int(w * 1.35), int(h * 0.75)), fill=(10, 60, 78))
    d.ellipse((int(w * -0.25), int(h * 0.55), int(w * 0.45), int(h * 1.4)), fill=(46, 10, 18))
    glow = glow.filter(ImageFilter.GaussianBlur(160))
    img = Image.blend(base, glow, 0.55)
    stars = ImageDraw.Draw(img)
    for _ in range(260):
        x, y = rnd.randrange(w), rnd.randrange(h)
        b = rnd.choice((70, 90, 120, 160, 210))
        r = 1 if b < 200 else rnd.choice((1, 2))
        stars.ellipse((x - r / 2, y - r / 2, x + r / 2, y + r / 2), fill=(b, b, min(255, b + 15)))
    buf = io.BytesIO()
    img.save(buf, "JPEG", quality=84, optimize=True, progressive=True)
    return buf.getvalue()


def mark(size=200):
    img = Image.open(MARK).convert("RGBA").resize((size, size), Image.LANCZOS)
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    return buf.getvalue()


def icon_png(size):
    buf = io.BytesIO()
    Image.open(ICON).convert("RGB").resize((size, size), Image.LANCZOS).save(buf, "PNG", optimize=True)
    return buf.getvalue()


def main():
    icons()
    bg, logo = background(), mark()
    small, large = icon_png(108), icon_png(512)
    OUT_TS.write_text(
        "// Generated by tools/alexa-assets/build_assets.py. Do not edit by hand.\n"
        "// Served by the alexa function at /alexa/assets/<name> (Echo Show screens).\n"
        "export const ASSETS: Record<string, { type: string; b64: string }> = {\n"
        f'  "bg.jpg": {{ type: "image/jpeg", b64: "{base64.b64encode(bg).decode()}" }},\n'
        f'  "orion.png": {{ type: "image/png", b64: "{base64.b64encode(logo).decode()}" }},\n'
        f'  "icon-108.png": {{ type: "image/png", b64: "{base64.b64encode(small).decode()}" }},\n'
        f'  "icon-512.png": {{ type: "image/png", b64: "{base64.b64encode(large).decode()}" }},\n'
        "};\n"
    )
    print(f"bg {len(bg) // 1024} KiB, mark {len(logo) // 1024} KiB -> {OUT_TS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
